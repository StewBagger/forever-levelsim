package database

import (
	"bytes"
	"encoding/json"
	"fmt"
	"os"

	"github.com/wowsims/forever/sim/core"
	"github.com/wowsims/forever/sim/levelsim"
	"google.golang.org/protobuf/encoding/protojson"
	googleProto "google.golang.org/protobuf/proto"
)

const healingGroupTSOutputPath = "ui/sim/proto/healing_group_auto_gen.ts"

// Mirrors levelsim's healing group into the UI, so a healer's level edit gives the group, the damage profile and the
// boss the level's healing sim runs with, with no sim call.
func GenerateHealingGroupTSFile() error {
	var buf bytes.Buffer
	buf.WriteString(`// Code generated by tools/database/gen_healing_group_ts.go. DO NOT EDIT.

import type { JsonObject } from '@protobuf-ts/runtime';

`)
	fmt.Fprintf(&buf, "// The target dummies beside the healer: the tank and the damage dealers (levelsim.HealingGroupDummies).\nexport const HEALING_GROUP_DUMMIES = %d;\n\n", levelsim.HealingGroupDummies)
	fmt.Fprintf(&buf, "// The raid index of the dummy in the tank slot (levelsim.HealingGroupTanks).\nexport const HEALING_GROUP_TANK_INDEX = %d;\n\n", levelsim.HealingGroupTanks()[0].Index)
	fmt.Fprintf(&buf, "// How far the boss sits above the group (levelsim.HealingGroupBossLevels).\nexport const HEALING_GROUP_BOSS_LEVELS = %d;\n\n", levelsim.HealingGroupBossLevels)

	writeLevels := func(comment, name string, of func(level int32) googleProto.Message) error {
		fmt.Fprintf(&buf, "// %s, in protojson, for levels 1 to %d from index 0.\nexport const %s: JsonObject[] = [\n", comment, core.CharacterLevel, name)
		for level := int32(1); level <= core.CharacterLevel; level++ {
			encoded, err := protojson.Marshal(of(level))
			if err != nil {
				return err
			}
			// protojson varies its spacing from run to run; compacted, the file is the same each time.
			var compact bytes.Buffer
			if err := json.Compact(&compact, encoded); err != nil {
				return err
			}
			fmt.Fprintf(&buf, "\t%s,\n", compact.String())
		}
		buf.WriteString("];\n")
		return nil
	}
	if err := writeLevels("levelsim.HealingGroupDamageProfile at each level", "HEALING_GROUP_DAMAGE_PROFILES", func(level int32) googleProto.Message {
		return levelsim.HealingGroupDamageProfile(level)
	}); err != nil {
		return err
	}
	buf.WriteString("\n")
	if err := writeLevels("levelsim.HealingGroupDummySettings at each level", "HEALING_GROUP_DUMMY_SETTINGS", func(level int32) googleProto.Message {
		return levelsim.HealingGroupDummySettings(level)
	}); err != nil {
		return err
	}

	if err := os.WriteFile(healingGroupTSOutputPath, buf.Bytes(), 0644); err != nil {
		return fmt.Errorf("failed to write generated healing group TS file: %w", err)
	}
	return nil
}
