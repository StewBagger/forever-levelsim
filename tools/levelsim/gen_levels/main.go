// Command gen_levels writes the per-level tables a character below level 60 sims with:
//
//   - sim/core/level_stats_auto_gen.go: base attributes, base mana, crit per Agility and Intellect per
//     class and level, and the creature health, armor and auto attack dps per level.
//   - sim/core/spelldata/unlevelled_auto_gen.go: the store spells with no SpellLevels row, which the
//     store writes as taught at 60 and which spelldata.LearnedRank reads as taught at 1.
//
// It reads tools/database/wowsims.db (make db) and assets/db_inputs/levelsim/player_class_stats.json.
//
//	go run ./tools/levelsim/gen_levels
package main

import (
	"database/sql"
	"encoding/json"
	"fmt"
	"log"
	"os"
	"os/exec"
	"sort"
	"strings"

	_ "modernc.org/sqlite"

	"github.com/wowsims/forever/sim/core/spelldata"
)

const (
	dbPath        = "tools/database/wowsims.db"
	classStats    = "assets/db_inputs/levelsim/player_class_stats.json"
	levelStatsOut = "sim/core/level_stats_auto_gen.go"
	unlevelledOut = "sim/core/spelldata/unlevelled_auto_gen.go"
	maxLevel      = 60
)

var classNames = map[int]string{1: "Warrior", 2: "Paladin", 3: "Hunter", 4: "Rogue", 5: "Priest", 7: "Shaman", 8: "Mage", 9: "Warlock", 11: "Druid"}

type classRow struct {
	ClassID   int `json:"classId"`
	Level     int `json:"level"`
	Health    int `json:"health"`
	Strength  int `json:"strength"`
	Agility   int `json:"agility"`
	Stamina   int `json:"stamina"`
	Intellect int `json:"intellect"`
	Spirit    int `json:"spirit"`
}

type expectedRow struct {
	baseMana                   int
	critPerAgi, spellCritPerInt float64
}

func main() {
	db, err := sql.Open("sqlite", dbPath)
	if err != nil {
		log.Fatal(err)
	}
	defer db.Close()

	writeLevelStats(db)
	writeUnlevelled(db)
}

func classIDs() []int {
	ids := make([]int, 0, len(classNames))
	for id := range classNames {
		ids = append(ids, id)
	}
	sort.Ints(ids)
	return ids
}

func writeLevelStats(db *sql.DB) {
	raw, err := os.ReadFile(classStats)
	if err != nil {
		log.Fatal(err)
	}
	var file struct{ Rows []classRow }
	if err := json.Unmarshal(raw, &file); err != nil {
		log.Fatal(err)
	}
	attrs := map[[2]int]classRow{}
	for _, r := range file.Rows {
		attrs[[2]int{r.ClassID, r.Level}] = r
	}

	expected := map[[2]int]expectedRow{}
	rows, err := db.Query(`SELECT ClassID, Level, BaseMana, CritPerAgility, SpellCritPerIntellect
		FROM PlayerExpectedStat WHERE ContentSetID = 0 AND Level BETWEEN 1 AND ?`, maxLevel)
	if err != nil {
		log.Fatal(err)
	}
	for rows.Next() {
		var c, l int
		var e expectedRow
		if err := rows.Scan(&c, &l, &e.baseMana, &e.critPerAgi, &e.spellCritPerInt); err != nil {
			log.Fatal(err)
		}
		expected[[2]int{c, l}] = e
	}
	rows.Close()

	var b strings.Builder
	b.WriteString("package core\n\n// Code generated by tools/levelsim/gen_levels. DO NOT EDIT.\n\n")
	b.WriteString("import (\n\t\"github.com/wowsims/forever/sim/core/proto\"\n\t\"github.com/wowsims/forever/sim/core/stats\"\n)\n\n")

	b.WriteString("// Base health, mana and primary attributes per class, indexed by level (1-60), before race offsets\n")
	b.WriteString("// and attack power. Attributes and health are AzerothCore's player_class_stats; mana is the game\n")
	b.WriteString("// files' PlayerExpectedStat.BaseMana.\n")
	b.WriteString("var classBaseStatsByLevel = map[proto.Class][61]stats.Stats{\n")
	for _, c := range classIDs() {
		fmt.Fprintf(&b, "\tproto.Class_Class%s: {\n", classNames[c])
		for l := 1; l <= maxLevel; l++ {
			a, ok := attrs[[2]int{c, l}]
			if !ok {
				log.Fatalf("player_class_stats has no row for class %d level %d", c, l)
			}
			e, ok := expected[[2]int{c, l}]
			if !ok {
				log.Fatalf("PlayerExpectedStat has no row for class %d level %d", c, l)
			}
			fmt.Fprintf(&b, "\t\t%d: {stats.Health: %d, stats.Mana: %d, stats.Strength: %d, stats.Agility: %d, stats.Stamina: %d, stats.Intellect: %d, stats.Spirit: %d},\n",
				l, a.Health, e.baseMana, a.Strength, a.Agility, a.Stamina, a.Intellect, a.Spirit)
		}
		b.WriteString("\t},\n")
	}
	b.WriteString("}\n\n")

	writeClassTable := func(name, doc string, value func(expectedRow) float64) {
		fmt.Fprintf(&b, "// %s\nvar %s = map[proto.Class][61]float64{\n", doc, name)
		for _, c := range classIDs() {
			fmt.Fprintf(&b, "\tproto.Class_Class%s: {", classNames[c])
			for l := 1; l <= maxLevel; l++ {
				fmt.Fprintf(&b, "%d: %.8f, ", l, value(expected[[2]int{c, l}])*100)
			}
			b.WriteString("},\n")
		}
		b.WriteString("}\n\n")
	}
	writeClassTable("critPerAgiByLevel", "Melee crit percent per point of Agility, by class and level (PlayerExpectedStat.CritPerAgility).",
		func(e expectedRow) float64 { return e.critPerAgi })
	writeClassTable("critPerIntByLevel", "Spell crit percent per point of Intellect, by class and level (PlayerExpectedStat.SpellCritPerIntellect).",
		func(e expectedRow) float64 { return e.spellCritPerInt })

	b.WriteString("// ExpectedStat's creature health, armor and auto attack dps by level, the base a pet's stats scale from.\n")
	b.WriteString("var creatureStatsByLevel = [61]struct{ Health, Armor, AutoAttackDps float64 }{\n")
	cr, err := db.Query(`SELECT Lvl, CreatureHealth, CreatureArmor, CreatureAutoAttackDps
		FROM ExpectedStat WHERE ContentSetID = 0 AND Lvl BETWEEN 1 AND ? ORDER BY Lvl`, maxLevel)
	if err != nil {
		log.Fatal(err)
	}
	seen := 0
	for cr.Next() {
		var l int
		var h, a, d float64
		if err := cr.Scan(&l, &h, &a, &d); err != nil {
			log.Fatal(err)
		}
		fmt.Fprintf(&b, "\t%d: {%v, %v, %v},\n", l, h, a, d)
		seen++
	}
	cr.Close()
	if seen != maxLevel {
		log.Fatalf("ExpectedStat has %d rows for levels 1-%d, want one per level", seen, maxLevel)
	}
	b.WriteString("}\n")

	writeGo(levelStatsOut, b.String())
}

func writeUnlevelled(db *sql.DB) {
	levelled := map[int32]bool{}
	rows, err := db.Query(`SELECT DISTINCT SpellID FROM SpellLevels`)
	if err != nil {
		log.Fatal(err)
	}
	for rows.Next() {
		var id int32
		if err := rows.Scan(&id); err != nil {
			log.Fatal(err)
		}
		levelled[id] = true
	}
	rows.Close()

	var ids []int32
	for _, s := range spelldata.All() {
		if !levelled[s.ID] && s.SpellLevel == maxLevel && s.BaseLevel == maxLevel && s.MaxLevel == 0 {
			ids = append(ids, s.ID)
		}
	}

	var b strings.Builder
	b.WriteString("package spelldata\n\n// Code generated by tools/levelsim/gen_levels. DO NOT EDIT.\n\n")
	b.WriteString("// The store spells with no SpellLevels row. The store writes them as taught at 60, with no scaling.\n")
	b.WriteString("var unlevelled = map[int32]bool{\n")
	for _, id := range ids {
		fmt.Fprintf(&b, "\t%d: true,\n", id)
	}
	b.WriteString("}\n")
	writeGo(unlevelledOut, b.String())
	log.Printf("%d store spells have no SpellLevels row", len(ids))
}

func writeGo(path, src string) {
	if err := os.WriteFile(path, []byte(src), 0o644); err != nil {
		log.Fatal(err)
	}
	if out, err := exec.Command("gofmt", "-w", path).CombinedOutput(); err != nil {
		log.Fatalf("gofmt %s: %v\n%s", path, err, out)
	}
}
